# Seed the New Money University catalog to match new-money-site.42bucks.com:
# the five live "directions" as full Russian courses and the three announced
# ones as upcoming placeholders, each with a branded card image.
# Idempotent. Card PNGs are read from CARDS_DIR (docker cp them in first):
#   bench --site new-money.42bucks.com execute lms.seed_nmu_site.run

import json
import os

import frappe

CARDS_DIR = "/tmp/nmu-cards"
CATEGORY = "Заработок"
INSTRUCTOR = "dean@new-money.42bucks.com"


def block(kind, **data):
	return {"id": frappe.generate_hash(length=10), "type": kind, "data": data}


def content(*blocks):
	return json.dumps({"time": 1754812800000, "blocks": list(blocks), "version": "2.29.0"})


def para(text):
	return block("paragraph", text=text)


def head(text, level=3):
	return block("header", text=text, level=level)


def attach_card(course, slug):
	path = os.path.join(CARDS_DIR, f"{slug}.png")
	if course.image or not os.path.exists(path):
		return
	from frappe.utils.file_manager import save_file

	with open(path, "rb") as f:
		file_doc = save_file(f"card-{slug}.png", f.read(), "LMS Course", course.name, is_private=0)
	course.reload()
	course.image = file_doc.file_url
	course.save()


def ensure_course(spec):
	existing = frappe.db.exists("LMS Course", {"title": spec["title"]})
	if existing:
		course = frappe.get_doc("LMS Course", existing)
	else:
		course = frappe.new_doc("LMS Course")
		course.update(
			{
				"title": spec["title"],
				"category": CATEGORY,
				"tags": spec.get("tags", ""),
				"published": 1,
				"upcoming": 1 if spec.get("upcoming") else 0,
				"published_on": frappe.utils.now(),
				"instructors": [{"instructor": INSTRUCTOR}],
				"short_introduction": spec["intro"],
				"description": spec["description"],
			}
		)
		course.save()

	attach_card(course, spec["slug"])

	for chapter_spec in spec.get("chapters", []):
		chapter_name = frappe.db.exists(
			"Course Chapter", {"course": course.name, "title": chapter_spec["title"]}
		)
		if chapter_name:
			chapter = frappe.get_doc("Course Chapter", chapter_name)
		else:
			chapter = frappe.new_doc("Course Chapter")
			chapter.course = course.name
			chapter.title = chapter_spec["title"]
			chapter.save()
			course.reload()
			course.append("chapters", {"chapter": chapter.name})
			course.save()

		for lesson_title, lesson_content in chapter_spec["lessons"]:
			if frappe.db.exists(
				"Course Lesson",
				{"course": course.name, "chapter": chapter.name, "title": lesson_title},
			):
				continue
			lesson = frappe.new_doc("Course Lesson")
			lesson.course = course.name
			lesson.chapter = chapter.name
			lesson.title = lesson_title
			lesson.content = lesson_content
			lesson.save()
			chapter.reload()
			chapter.append("lessons", {"lesson": lesson.name})
			chapter.save()
	return course


